#!/usr/bin/env bash
#
# build-vault-index.sh — regenerate the vault index ad-hoc tasks check before
# falling back to a full Glob/Grep sweep.
#
# Walks every note under $VAULT, pulls its title (first `# ` heading, else
# filename) and frontmatter `type`/`tags`, and writes one manifest grouped by
# top-level folder to $VAULT/.vault-index/INDEX.md. The leading dot keeps it
# out of Obsidian's file browser -- it's a machine artifact, not a note.
#
# Cheap by design: no LLM call, just find/sed over markdown files, so
# queue-runner.sh can afford to check staleness on every --now tick.
#
# Only reads single-line frontmatter values, same as queue-runner.sh's own
# `fm()` -- a multi-line YAML list like `tags:\n  - foo` is skipped, not
# parsed. Good enough for an outline; not a YAML parser.
#
# Usage: build-vault-index.sh [vault-path]

set -euo pipefail

VAULT="${1:-${VAULT:-$HOME/vault}}"
INDEX_DIR="$VAULT/.vault-index"
OUT="$INDEX_DIR/INDEX.md"
EXCLUDE_REGEX='/\.obsidian/|/\.vault-index/|/00_Inbox/Agent_Results/'

mkdir -p "$INDEX_DIR"

title_of() {
  grep -m1 '^# ' "$1" 2>/dev/null | sed 's/^# *//' || basename "$1" .md
}

fm_field() {
  sed -n '/^---[[:space:]]*$/,/^---[[:space:]]*$/p' "$2" 2>/dev/null \
    | sed -n "s/^$1:[[:space:]]*//p" | head -1 | tr -d '\r'
}

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

{
  echo '---'
  echo 'type: vault-index'
  echo "generated: $(date -Iseconds)"
  echo '---'
  echo
  echo '# Vault index'
  echo
  echo 'Machine-generated by `bin/build-vault-index.sh`, rebuilt whenever a'
  echo 'note changes (see `bin/queue-runner.sh`). Check here before a full'
  echo 'Glob/Grep sweep of the vault; fall back to Glob/Grep for anything'
  echo 'this lags or does not cover.'
  echo
} >"$tmp"

{
  current_folder=""
  while IFS= read -r note; do
    rel="${note#"$VAULT"/}"
    if [[ "$rel" == */* ]]; then
      folder="${rel%%/*}"
    else
      folder="(root)"
    fi
    if [[ "$folder" != "$current_folder" ]]; then
      [[ -n "$current_folder" ]] && echo
      echo "## $folder"
      echo
      current_folder="$folder"
    fi
    title="$(title_of "$note")"
    ftype="$(fm_field type "$note")"
    tags="$(fm_field tags "$note")"
    meta=""
    [[ -n "$ftype" ]] && meta="type:$ftype"
    [[ -n "$tags" ]] && meta="${meta:+$meta }tags:$tags"
    if [[ -n "$meta" ]]; then
      echo "- [$title]($rel) — $meta"
    else
      echo "- [$title]($rel)"
    fi
  done < <(find "$VAULT" -type f -name '*.md' | grep -vE "$EXCLUDE_REGEX" | sort)
} >>"$tmp"

results_count=0
if [[ -d "$VAULT/00_Inbox/Agent_Results" ]]; then
  results_count="$(find "$VAULT/00_Inbox/Agent_Results" -maxdepth 1 -name '*.md' | wc -l)"
fi
{
  echo
  echo '## 00_Inbox/Agent_Results'
  echo
  echo "$results_count result note(s) at the top level, plus anything"
  echo 'archived under `_archive/YYYY-MM/` (retention runs in'
  echo '`bin/queue-runner.sh --drain`). Excluded from the listing above --'
  echo 'agent output, not curated notes. Grep it directly for past results.'
} >>"$tmp"

mv "$tmp" "$OUT"
trap - EXIT
